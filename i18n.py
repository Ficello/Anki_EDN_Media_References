def get_current_language() -> str:
    """Détecte le code de langue actuel d'Anki (ex: 'fr', 'en', 'es', 'de')."""
    try:
        from aqt import mw
        if mw and hasattr(mw, "pm") and mw.pm:
            # Anki 2.1.50+
            meta_lang = mw.pm.meta.get("lang")
            if meta_lang:
                return meta_lang.split("_")[0].lower()
    except Exception:
        pass

    try:
        from anki.lang import current_lang
        if current_lang:
            return current_lang.split("_")[0].lower()
    except Exception:
        pass

    return "fr"


def tr(key: str, **kwargs) -> str:
    """Traduit une chaîne selon la langue active d'Anki, avec repli vers l'anglais ou le français."""
    lang = get_current_language()
    dict_lang = TRANSLATIONS.get(lang) or TRANSLATIONS.get("en") or TRANSLATIONS["fr"]
    text = dict_lang.get(key) or TRANSLATIONS["en"].get(key) or TRANSLATIONS["fr"].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except Exception:
            pass
    return text
